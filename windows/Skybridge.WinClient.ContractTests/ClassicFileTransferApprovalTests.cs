using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Skybridge.WinClient.Services.FileTransfer;

internal static class ClassicFileTransferApprovalTests
{
    internal static IEnumerable<(string Name, Func<Task> Run)> Cases =>
    [
        ("classic metadata-bound approval matches independent Apple vectors without changing legacy bytes", Golden),
        ("classic approval rejects altered metadata downgrade contradictory decisions and forged tags", Boundaries),
        ("classic approval framing rejects oversized payloads before allocation", FrameBounds),
        ("classic approval withdrawal before or during a write cannot publish an authenticated grant", Withdrawal)
    ];
    private static readonly byte[] Key = Enumerable.Repeat((byte)0x42, 32).ToArray();
    private static ClassicFileMetadata Metadata() => ClassicFileTransferWire.Authenticate(
        new ClassicFileMetadata("t", "f", 0, new string('a', 64), 65536, 2,
            ApprovalProtocol: ClassicFileTransferWire.ApprovalProtocol), Key);
    private static void Require(bool value, string reason) { if (!value) throw new InvalidOperationException(reason); }
    private static void Reject<T>(Action action) where T : Exception
    { try { action(); } catch (T) { return; } throw new InvalidOperationException($"Expected {typeof(T).Name}."); }
    private static async Task Reject<T>(Func<Task> action) where T : Exception
    { try { await action(); } catch (T) { return; } throw new InvalidOperationException($"Expected {typeof(T).Name}."); }

    private static Task Golden()
    {
        // Published in the Apple workspace's ClassicTransferApprovalVectorTests;
        // these constants are not generated by the implementation under test.
        var metadata = Metadata();
        Require(Convert.ToHexStringLower(metadata.MetadataAuthTag!) ==
            "4161c9e87976df430d2a7231cfbc014f013b1a52ecb12b54a1d37845b1142173", "Extended metadata MAC differs from Apple.");
        foreach (var (reason, tag) in new (string?, string)[]
        {
            (null, "26108f405d37a73ba8e1416f10cbf38430da76367ae0548a495a99ad67cca83a"),
            ("denied", "d7c4128567c1e9c6862fbd9821b36df5de2d03c718173b931b44da82e94ee9ce"),
            ("unavailable", "182ac62ae216942dd4be1912f9e6692e58060165d72ff929846e16f95a3e593e")
        })
        {
            var response = ClassicFileTransferWire.CreateApproval(metadata, Key, reason);
            Require(response.MetadataDigest == "79fe81f7847c8e51a276141af4d2269d1bb0b6e2eb088cc280268e150917f17d" &&
                Convert.ToHexStringLower(response.AuthTag) == tag, "Approval transcript differs from Apple.");
            var decoded = ClassicFileTransferWire.Decode<ClassicFileApproval>(ClassicFileTransferWire.Encode(response));
            Require(ClassicFileTransferWire.VerifyApproval(decoded, metadata, Key) == reason && decoded.Accepted == (reason is null),
                "A refusal changed into permission or approval lost its binding.");
        }
        var legacy = metadata with { ApprovalProtocol = null, MetadataAuthTag = null };
        Require(!Encoding.UTF8.GetString(ClassicFileTransferWire.Encode(legacy)).Contains("approvalProtocol", StringComparison.Ordinal),
            "Absent approval changed the legacy JSON payload.");
        return Task.CompletedTask;
    }

    private static Task Boundaries()
    {
        var metadata = Metadata(); var grant = ClassicFileTransferWire.CreateApproval(metadata, Key);
        Reject<CryptographicException>(() => ClassicFileTransferWire.Verify(metadata with { ApprovalProtocol = null }, Key));
        var legacy = ClassicFileTransferWire.Authenticate(metadata with { ApprovalProtocol = null }, Key);
        Reject<CryptographicException>(() => ClassicFileTransferWire.Verify(legacy with { ApprovalProtocol = ClassicFileTransferWire.ApprovalProtocol }, Key));
        Reject<InvalidDataException>(() => ClassicFileTransferWire.CreateApproval(legacy, Key));
        Reject<InvalidDataException>(() => ClassicFileTransferWire.Authenticate(metadata with { ApprovalProtocol = "future" }, Key));
        var different = ClassicFileTransferWire.Authenticate(metadata with { FileName = "other" }, Key);
        Reject<InvalidDataException>(() => ClassicFileTransferWire.VerifyApproval(grant, different, Key));
        foreach (var wrong in new[]
        {
            grant with { TransferId = "other" }, grant with { MetadataDigest = new string('b', 64) },
            grant with { Accepted = false }, grant with { Reason = "denied" }, grant with { Reason = "unknown", Accepted = false },
            grant with { SecurityVersion = 1 }, grant with { MetadataDigest = new string('A', 64) }
        }) Reject<InvalidDataException>(() => ClassicFileTransferWire.VerifyApproval(wrong, metadata, Key));
        var tag = grant.AuthTag.ToArray(); tag[0] ^= 1;
        Reject<CryptographicException>(() => ClassicFileTransferWire.VerifyApproval(grant with { AuthTag = tag }, metadata, Key));
        Reject<CryptographicException>(() => ClassicFileTransferWire.VerifyApproval(grant with { AuthTag = [] }, metadata, Key));
        var json = Encoding.UTF8.GetString(ClassicFileTransferWire.Encode(grant));
        Reject<JsonException>(() => ClassicFileTransferWire.Decode<ClassicFileApproval>(Encoding.UTF8.GetBytes(
            json.Replace("\"accepted\":true", "\"accepted\":true,\"accepted\":false", StringComparison.Ordinal))));
        return Task.CompletedTask;
    }

    private static async Task FrameBounds()
    {
        using var stream = new MemoryStream();
        var payload = ClassicFileTransferWire.Encode(ClassicFileTransferWire.CreateApproval(Metadata(), Key));
        await ClassicFileTransferFrames.WriteAsync(stream, ClassicFileFrameType.Approval, payload, default);
        Require(stream.ToArray()[3] == 7, "Approval changed its Apple wire opcode."); stream.Position = 0;
        var frame = await ClassicFileTransferFrames.ReadAsync(stream, default);
        Require(frame.Type == ClassicFileFrameType.Approval && frame.Payload.SequenceEqual(payload), "Approval framing changed the payload.");
        foreach (var header in new byte[][] { [0,0,0,7,0,0,8,1], [0,0,0,7,0,0,0,0], [0,0,0,6,0,0,0,1] })
        {
            using var input = new MemoryStream(header);
            await Reject<InvalidDataException>(() => ClassicFileTransferFrames.ReadAsync(input, default));
            Require(input.Position == 8, "Approval bound was not enforced at the header.");
        }
    }

    private static async Task Withdrawal()
    {
        bool current = false;
        void RequireCurrent() { if (!current) throw new InvalidOperationException("Approval withdrawn."); }
        using var stream = new RevokeAfterHeader(() => current = false);
        await Reject<InvalidOperationException>(() => ClassicFileTransferOperation.SendApprovalAsync(stream, Metadata(), Key, null, RequireCurrent, default));
        Require(stream.Length == 0, "A withdrawn grant wrote bytes.");
        current = true;
        await Reject<InvalidOperationException>(() => ClassicFileTransferOperation.SendApprovalAsync(stream, Metadata(), Key, null, RequireCurrent, default));
        Require(stream.Length == 8, "Withdrawal after the header still wrote an authenticated payload.");
        using var foreign = new CancellationTokenSource(); foreign.Cancel();
        var expected = new OperationCanceledException(foreign.Token);
        using var untouched = new MemoryStream(); int checks = 0;
        try
        {
            await ClassicFileTransferOperation.SendApprovalAsync(untouched, Metadata(), Key, null, () =>
            {
                if (++checks == 2) throw expected; // Inside the actual framed-write boundary.
            }, default);
            throw new InvalidOperationException("Foreign cancellation was ignored.");
        }
        catch (OperationCanceledException actual)
        { Require(ReferenceEquals(actual, expected) && untouched.Length == 0, "Authority cancellation became a transport timeout or wrote a grant."); }
    }
    private sealed class RevokeAfterHeader(Action revoke) : MemoryStream
    {
        public override async ValueTask WriteAsync(ReadOnlyMemory<byte> bytes, CancellationToken token = default)
        { await base.WriteAsync(bytes, token); revoke(); }
    }
}
